const code = `var fonts = FontGroup.builder()
        .fontFile("fonts/regular.ttf")
        .build();
var engine = DocumentEngine.builder(fonts).build();

var document = Document.builder()
        .heading("Quarterly report", 1)
        .paragraph("A report with automatic pagination.")
        .table(List.of("Metric", "Value"),
                List.of(List.of("Revenue", "120")))
        .build();

engine.write(document, new PdfBackend(), "report.pdf");`

const codeParts = computed(() => {
  const pattern = /"(?:\\.|[^"\\])*"|\b(?:var|new)\b|\b(?:FontGroup|DocumentEngine|Document|PdfBackend|List)\b|\b\d+\b/g
  const parts: { text: string, type: string }[] = []
  let offset = 0
  for (const match of code.matchAll(pattern)) {
    const index = match.index ?? 0
    if (index > offset) parts.push({ text: code.slice(offset, index), type: '' })
    const text = match[0]
    const type = text.startsWith('"') ? 'string' : /^\d/.test(text) ? 'number' : /^(var|new)$/.test(text) ? 'keyword' : 'type'
    parts.push({ text, type })
    offset = index + text.length
  }
  if (offset < code.length) parts.push({ text: code.slice(offset), type: '' })
  return parts
})

async function copyCode() {
  try {
    await navigator.clipboard.writeText(code)
    copyState.value = 'copied'
  } catch {
    copyState.value = 'failed'
  }
}
