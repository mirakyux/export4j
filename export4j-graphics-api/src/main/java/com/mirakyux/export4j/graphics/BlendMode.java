package com.mirakyux.export4j.graphics;

/** ISO 32000 source-over blend functions. Non-separable modes use the specification's luminosity/saturation functions. */
public enum BlendMode {
    NORMAL, MULTIPLY, SCREEN, OVERLAY, DARKEN, LIGHTEN, COLOR_DODGE, COLOR_BURN,
    HARD_LIGHT, SOFT_LIGHT, DIFFERENCE, EXCLUSION, HUE, SATURATION, COLOR, LUMINOSITY
}
